#!/bin/sh
# Writes game/src/ext/hook_points.gd: the names of every hook point (Hooks.has / before / after) and value point
# (Hooks.has_value / value) in the game's code, game/src and game/flash, built-in extensions included. Extensions
# check the names they register against it (SDTExtension.hook_before / hook_after / modify), so a typo or a point
# that was removed shows up as a warning when the extension is switched on, not as a hook that never runs.
#   sh tools/gen_hook_points.sh           rewrite the file
#   sh tools/gen_hook_points.sh --check   only report (exit 1) when the file is out of date (tools/check_all.sh)
# Only literal names (&"Class.method") are found; a point whose name is built at run time is not listed.
cd "$(dirname "$0")/.." || exit 1
OUT=game/src/ext/hook_points.gd

names() {   # $1: grep pattern for the Hooks functions
	grep -rhoE --include='*.gd' "Hooks\.($1)\(&\"[A-Za-z0-9_.]+\"" game/src game/flash \
		| sed -E 's/.*&"//; s/"$//' | LC_ALL=C sort -u
}

if [ -z "$EXT_DIRS" ]; then   # where extensions live (EXT_DIRS="..." to check other folders)
	EXT_DIRS="game/src/ext"
	[ -d Mods/Plugins ] && EXT_DIRS="$EXT_DIRS Mods/Plugins"
fi

used() {   # "file:line name" for every literal name passed to the functions in $1 by extensions and plugins
	# shellcheck disable=SC2086
	grep -rnoE --include='*.gd' "(^|[^A-Za-z0-9_])($1)\(&\"[A-Za-z0-9_.]+\"" $EXT_DIRS \
		| sed -E 's/^(.*):([0-9]+):.*&"([^"]+)"$/\1:\2 \3/' | LC_ALL=C sort -u
}

declared() {   # names declared with declare_hook_point / declare_value_point ($1: hook or value)
	# shellcheck disable=SC2086
	grep -rhoE --include='*.gd' "declare_$1_point\(&\"[A-Za-z0-9_.]+\"" $EXT_DIRS | sed -E 's/.*&"//; s/"$//'
}

entries() {
	while read -r n; do
		printf '\t&"%s": true,\n' "$n"
	done
}

generate() {
	printf '%s\n' 'extends RefCounted' \
		'## Generated by tools/gen_hook_points.sh from the game'"'"'s code; do not edit. Rerun the tool after adding or removing' \
		'## a hook point or value point (tools/check_all.sh reports when this list is out of date).' \
		'' \
		'## Hook points: Hooks.has / before / after in game code (SDTExtension.hook_before / hook_after).' \
		'const HOOKS := {'
	names 'has|before|after' | entries
	printf '%s\n' '}' '' \
		'## Value points: Hooks.has_value / value in game code (SDTExtension.modify).' \
		'const VALUES := {'
	names 'has_value|value' | entries
	printf '%s\n' '}'
}

if [ "$1" = "--check" ]; then
	if ! generate | cmp -s - "$OUT"; then
		echo "hook points: $OUT is out of date, run: sh tools/gen_hook_points.sh"
		exit 1
	fi
	hooks=$(names 'has|before|after'; declared hook)
	values=$(names 'has_value|value'; declared value)
	report=$(
		# every value point should be described in the docs' table
		names 'has_value|value' | while read -r n; do
			grep -qF "\`$n\`" docs/extensions.md || echo "hook points: value point $n is not in docs/extensions.md"
		done
		# names that built-in extensions and plugins register (literal ones) must exist, in the game or declared
		used 'hook_before|hook_after|Hooks\.add_before|Hooks\.add_after' | while read -r u; do
			printf '%s\n' "$hooks" | grep -qxF "${u##* }" \
				|| echo "hook points: ${u% *} uses hook point ${u##* }, which the game does not have"
		done
		used 'modify|unmodify|Hooks\.add_modifier|Hooks\.remove_modifiers' | while read -r u; do
			printf '%s\n' "$values" | grep -qxF "${u##* }" \
				|| echo "hook points: ${u% *} uses value point ${u##* }, which the game does not have"
		done
	)
	[ -z "$report" ] && exit 0
	printf '%s\n' "$report"
	exit 1
fi
generate > "$OUT"
echo "$OUT: $(names 'has|before|after' | wc -l) hook points, $(names 'has_value|value' | wc -l) value points"
